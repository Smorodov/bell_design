#include "ccx_input_writer.hpp"

#include <fstream>

namespace BellOptimizer {

bool CCXInputWriter::write(const BellMeshData& mesh,
                           const BellMaterial& material,
                           const std::string& filename,
                           int requested_modes) {
    if (mesh.nodes.empty() || mesh.elements.empty() || requested_modes < 1) return false;

    std::ofstream file(filename);
    if (!file) return false;

    file << "*HEADING\n";
    file << "Bell - axisymmetric mesh generated by BellGenerator\n";
    file << "*MATERIAL, NAME=BRONZE\n";
    file << "*ELASTIC\n";
    file << material.E << ", " << material.nu << "\n";
    file << "*DENSITY\n";
    file << material.rho << "\n";

    file << "*NODE, NSET=Nall\n";
    for (const auto& node : mesh.nodes)
        file << node.id << ", " << node.r << ", " << node.z << "\n";

    file << "*ELEMENT, TYPE=CAX4, ELSET=Eall\n";
    for (size_t i = 0; i < mesh.elements.size(); ++i) {
        const auto& e = mesh.elements[i];
        file << (i + 1) << ", " << e.n1 << ", " << e.n2 << ", " << e.n3 << ", " << e.n4 << "\n";
    }

    file << "*SOLID SECTION, ELSET=Eall, MATERIAL=BRONZE\n";
    file << "*BOUNDARY\n";
    file << "1, 1, 1, 0.0\n";
    int axis_node = 0;
    for (const auto& node : mesh.nodes) {
        if (node.id != 1 && node.r >= -1e-12 && node.r <= 1e-12) {
            axis_node = node.id;
            break;
        }
    }
    if (axis_node > 0) file << axis_node << ", 1, 1, 0.0\n";

    file << "*STEP\n";
    file << "*FREQUENCY, STORAGE=YES\n";
    file << requested_modes << "\n";
    file << "*NODE FILE, OUTPUT=2D\n";
    file << "U\n";
    file << "*END STEP\n";
    return static_cast<bool>(file);
}

} // namespace BellOptimizer
